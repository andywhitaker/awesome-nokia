// Helper functions for filtering and search
export function getAllTags(): string[] {
  const tagSet = new Set<string>();
  RESOURCES.forEach((r) => r.tags.forEach((t) => tagSet.add(t)));
  return Array.from(tagSet).sort();
}

export function getResourcesByCategory(categoryId: CategoryId): Resource[] {
  return RESOURCES.filter((r) => r.category === categoryId);
}

export function getCategoryById(categoryId: CategoryId): Category | undefined {
  return CATEGORIES.find((c) => c.id === categoryId);
}
